/* ── Language management ── */
let currentLang = localStorage.getItem('wt_lang') || 'ar';

function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['ar'][key] || key;
}

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('wt_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = TRANSLATIONS[lang].dir;

  // Apply translations to all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[lang][key] !== undefined) {
      el.innerHTML = TRANSLATIONS[lang][key];
    }
  });

  // Apply placeholder translations
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (TRANSLATIONS[lang][key] !== undefined) {
      el.placeholder = TRANSLATIONS[lang][key];
    }
  });

  // Update active lang btn
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Update currency labels
  document.querySelectorAll('.currency-label').forEach(el => {
    el.textContent = t('currency');
  });

  // Dispatch event for popup updates
  document.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));

  // Update product names/descriptions shown in product cards
  document.querySelectorAll('.product-card').forEach(card => {
    const nameAr = card.dataset.nameAr || '';
    const nameFr = card.dataset.nameFr || '';
    const nameEn = card.dataset.nameEn || '';
    const nameEl = card.querySelector('.product-name');
    if (nameEl) {
      nameEl.textContent = lang === 'ar' ? nameAr : (lang === 'fr' ? (nameFr || nameEn || nameAr) : (nameEn || nameAr));
    }

    const descAr = card.dataset.descAr || '';
    const descFr = card.dataset.descFr || '';
    const descEn = card.dataset.descEn || '';
    const descEl = card.querySelector('.product-desc-text');
    if (descEl) {
      descEl.textContent = lang === 'ar' ? descAr : (lang === 'fr' ? (descFr || descEn || descAr) : (descEn || descAr));
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  // Create lang switcher
  const switcher = document.getElementById('lang-switcher');
  if (switcher) {
    switcher.innerHTML = `
      <button class="lang-btn${currentLang === 'ar' ? ' active' : ''}" data-lang="ar">AR</button>
      <button class="lang-btn${currentLang === 'fr' ? ' active' : ''}" data-lang="fr">FR</button>
      <button class="lang-btn${currentLang === 'en' ? ' active' : ''}" data-lang="en">EN</button>
    `;
    switcher.addEventListener('click', e => {
      const btn = e.target.closest('.lang-btn');
      if (btn) applyLang(btn.dataset.lang);
    });
  }
  applyLang(currentLang);
});
